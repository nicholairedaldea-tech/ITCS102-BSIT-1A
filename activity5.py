#Operator
# + - Addition
# - - Subtraction
# * - Multiplication
# / - Division
# % - Modulus
# ** - Exponent
# // - Floor Division

x= 30
y= 5

sum= x + y
difference= x - y
product= x * y
div= x / y
mod= x % y
exp= x ** y
fd= x // y


print("The sum of", x, "and", y, "is", sum)
print("The difference of", x, "and", y, "is", difference)
print("The product of", x, "and", y, "is", product)
print("When", x, "is divided by", y, "the answer is", div)
print("The modulus of", x, "and", y, "is", mod)
print("When", x, "is raised to", y, "the answer will be", exp)
print("When", x, "is floor divided by", y, "the answer will be", fd)